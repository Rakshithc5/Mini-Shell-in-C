#include "main.h"

// Store external commands
char **externalcmds;

// Store all jobs
Job jobs[MAX_JOBS];

// Keep track of number of jobs
int job_count = 0;

// Store shell process group ID
pid_t shell_pgid = -1;

// Store foreground process group ID
pid_t foreground_pgid = -1;

// Store shell terminal
int shell_terminal = STDIN_FILENO;

// Store last command status
int last_status = 0;

// Store shell prompt
char prompt[MAX_INPUT_SIZE] = "minishell$ ";

static void forward_signal(int sig)
{
    // Send signal to foreground process group
    if (foreground_pgid > 0)
    {
        kill(-foreground_pgid, sig);
        return;
    }

    // Handle Ctrl+C
    if (sig == SIGINT)
    {
        write(STDOUT_FILENO, "\n", 1);
        write(STDOUT_FILENO, prompt, strlen(prompt));
    }
    // Handle Ctrl+Z
    else if (sig == SIGTSTP)
    {
        write(STDOUT_FILENO, "\n", 1);
        write(STDOUT_FILENO, prompt, strlen(prompt));
    }
}

static void init_shell(void)
{
    pid_t pid;

    // Make sure the shell is in the foreground
    while (tcgetpgrp(shell_terminal) != (pid = getpgrp()))
        kill(-pid, SIGTTIN);

    struct sigaction sa;

    // Initialize signal handler
    memset(&sa, 0, sizeof(sa));
    sa.sa_handler = forward_signal;
    sigemptyset(&sa.sa_mask);
    sa.sa_flags = 0;

    // Set handlers for Ctrl+C and Ctrl+Z
    sigaction(SIGINT, &sa, NULL);
    sigaction(SIGTSTP, &sa, NULL);

    // Ignore terminal control signals
    signal(SIGTTIN, SIG_IGN);
    signal(SIGTTOU, SIG_IGN);

    // Set shell process group ID
    shell_pgid = getpid();

    // Put shell into its own process group
    if (setpgid(shell_pgid, shell_pgid) == -1 && errno != EACCES)
    {
        perror("setpgid");
        exit(1);
    }

    // Give terminal control to the shell
    if (tcsetpgrp(shell_terminal, shell_pgid) == -1)
    {
        perror("tcsetpgrp");
        exit(1);
    }
}

int main(void)
{
    char input[MAX_INPUT_SIZE];
    char shell_path[PATH_MAX];

    // Get the path of the shell executable
    if (realpath("/proc/self/exe", shell_path) == NULL)
        strcpy(shell_path, "minishell");

    // Set the SHELL environment variable
    setenv("SHELL", shell_path, 1);

    // Allocate memory for external commands
    externalcmds = calloc(500, sizeof(char *));
    if (!externalcmds)
    {
        perror("calloc");
        return 1;
    }

    // Load external commands from file
    extract_external_commands(externalcmds);

    // Initialize shell and signal handling
    init_shell();

    // Start reading user input
    scan_input(input);

    // Free memory used by external commands
    for (int i = 0; externalcmds[i]; i++)
        free(externalcmds[i]);

    // Free external command list
    free(externalcmds);
    return 0;
}